package logicnotes;

public class ForEach {
    public static void main(String[] args) {
        String [] cities = {"Medellín", "Sabaneta", "Envigado", "Bello", "Girardota", "Barbosa", "Copacabana", "Itagui", "La Estrella"};

        for(String city : cities) {
            System.out.println(city);
        }
    }
}
